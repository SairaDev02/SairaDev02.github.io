// Hover-while-Lyrics-open and Escape-mid-drag probes with correct disc coordinates (wide grid, 4 tracks).
import { chromium } from '@playwright/test';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const SITE = 'https://sairadev02.github.io/';
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), 'shots');
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 } });
const page = await ctx.newPage();
await page.goto(SITE, { waitUntil: 'networkidle' }); await page.waitForTimeout(1200);
const box = await page.locator('[data-player] canvas').boundingBox();
const px = (x, y) => [box.x + (x / 512) * box.width, box.y + (y / 224) * box.height];
const st = () => page.evaluate(() => ({ title: document.querySelector('[data-lyrics-title]').textContent, now: [...document.querySelectorAll('[data-lines] li:not(.tag)')].findIndex((l) => l.classList.contains('now')), dock: document.querySelector('[data-np-title]').textContent }));
await page.locator('[data-np-panel="lyrics"]').click();
await page.waitForTimeout(6000);
console.log('before hover', JSON.stringify(await st()));
await page.mouse.move(...px(202, 62), { steps: 4 }); await page.waitForTimeout(400);
console.log('hover disc 02 (visible above panel)', JSON.stringify(await st()));
await page.screenshot({ path: path.join(out, 'probe-hover-while-lyrics.png') });
await page.mouse.move(5, 5); await page.waitForTimeout(300);
console.log('pointer left', JSON.stringify(await st()));
await page.keyboard.press('Escape');
await page.mouse.move(...px(202, 62)); await page.mouse.down(); await page.mouse.move(...px(382, 112), { steps: 8 }); await page.waitForTimeout(300);
console.log('over tray LCD', await page.locator('[data-lcd-title]').textContent());
await page.keyboard.press('Escape'); await page.waitForTimeout(300);
console.log('after Escape (still pressed) LCD', await page.locator('[data-lcd-title]').textContent());
await page.mouse.move(...px(202, 150), { steps: 8 }); await page.waitForTimeout(300);
console.log('dragged back out LCD', await page.locator('[data-lcd-title]').textContent());
await page.mouse.up(); await page.waitForTimeout(500);
console.log('released in sky LCD', await page.locator('[data-lcd-title]').textContent(), page.url());
await browser.close();
